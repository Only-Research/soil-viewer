/**
 * Removes the tree at `target`, and **only** if `checkTarget` allows it and the marker is present.
 *
 * The marker check is repeated here rather than trusted from the caller. `checkTarget` runs at the
 * top of the build and this function is also public; a guard that only fires on one of two entry
 * points is the build's signature failure shape — *a control correct in isolation and never
 * reached*.
 *
 * Some of the hazards deliberately make themselves hard to delete: a directory at mode 0555 does
 * not permit its own children to be unlinked. The mode restoration below is what makes the tree
 * disposable, and it is confined to a tree already proven to carry the marker.
 */
export interface RemoveOptions {
  readonly repositoryRoot?: string
  readonly home?: string
  /**
   * **Test seam.** Runs after `checkTarget` and before the marker is confirmed — the only way
   * into the window the second marker check defends.
   *
   * It exists because a mutation sweep found that check GREEN: `checkTarget` already refuses any
   * existing directory without a marker, so in ordinary operation the second check is never the
   * one that fires, and deleting it changed nothing the tests could see. A control that cannot be
   * reached cannot be proven, and an unprovable control on a recursive delete is not a control —
   * it is a comment. Same pattern, and same reason, as `readBack` in
   * `src/core/fs/resolve-conflict.ts`.
   */
  readonly beforeMarkerCheck?: () => Promise<void>
}

export async function removeMockSoil(target: string, options: RemoveOptions = {}): Promise<boolean> {
  const repositoryRoot = options.repositoryRoot ?? await findRepositoryRoot()
  const verdict = await checkTarget(target, repositoryRoot, options.home)
  if (!verdict.ok) throw new Error(`Refusing to remove: ${verdict.reason}`)

  try {
    await fsp.lstat(target)
  } catch {
    return false // nothing there
  }

  if (options.beforeMarkerCheck) await options.beforeMarkerCheck()

  // Confirmed here explicitly rather than inferred from the verdict. `checkTarget` returns ok for
  // a path that does not exist yet, and its own marker check ran before the `lstat` above — so
  // between the two, the marker can go away. On a function that recursively deletes, the second
  // look is worth its cost.
  try {
    await fsp.stat(join(target, MARKER))
  } catch {
    throw new Error(`Refusing to remove "${target}": no "${MARKER}" file at the moment of removal. This tool only deletes trees it created.`)
  }

  await restoreModes(target)
  await fsp.rm(target, { recursive: true, force: true })
  return true
}

/** Makes every directory in the tree traversable and writable again, so removal can proceed. */
async function restoreModes(dir: string): Promise<void> {
  try {
    await fsp.chmod(dir, 0o755)
  } catch { /* best effort */ }
  let entries
  try {
    entries = await fsp.readdir(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    if (entry.isSymbolicLink()) continue
    if (entry.isDirectory()) await restoreModes(join(dir, entry.name))
  }
}
