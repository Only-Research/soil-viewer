/** Mulberry32. Deterministic by construction — no clock, no `Math.random`. */
function seeded(seed: number): () => number {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const NOUNS = [
  'allocation', 'bin count', 'bloom window', 'brix reading', 'cold chain', 'cull rate',
  'dump tank', 'grading standard', 'harvest window', 'intake curve', 'labour draw',
  'packing schedule', 'pick order', 'pollination', 'pressure test', 'rootstock', 'scab pressure',
  'spot price', 'storage loss', 'thinning pass', 'trellis spacing', 'water sample',
]
const VERBS = [
  'held flat against', 'came in under', 'ran ahead of', 'was revised after', 'now depends on',
  'contradicts', 'was measured against', 'stalls on', 'was deferred pending', 'confirms',
]
const QUALIFIERS = [
  'on one season of data', 'against the five-year mean', 'before the board voted',
  'without the packing house in the room', 'on Ardith and Kestrel only', 'in the 2025 numbers',
  'assuming the clause holds', 'at current staffing', 'if the weather behaves',
]
const FARMS = ['Hollis', 'Bray', 'Kestrel', 'Nine Mile', 'Ardith', 'Two Rivers', 'Larkspur']
const MONTHS = [
  'January', 'February', 'March', 'April', 'May', 'June',
  'July', 'August', 'September', 'October', 'November', 'December',
]

const pick = <T,>(rng: () => number, list: readonly T[]): T =>
  list[Math.floor(rng() * list.length)] as T

function sentence(rng: () => number): string {
  const shape = rng()
  if (shape < 0.25) {
    return `${pick(rng, FARMS)} reports the ${pick(rng, NOUNS)} ${pick(rng, VERBS)} the ${pick(rng, NOUNS)}, ${pick(rng, QUALIFIERS)}.`
  }
  if (shape < 0.5) {
    return `The ${pick(rng, NOUNS)} ${pick(rng, VERBS)} last year's figure — ${Math.floor(rng() * 900 + 100)} against ${Math.floor(rng() * 900 + 100)}.`
  }
  if (shape < 0.7) {
    return `Nobody has checked whether the ${pick(rng, NOUNS)} still holds ${pick(rng, QUALIFIERS)}.`
  }
  if (shape < 0.85) {
    return `Raised ${Math.floor(rng() * 27 + 1)} ${pick(rng, MONTHS)}; unresolved.`
  }
  return `**${pick(rng, FARMS)} disagrees**, and the disagreement is about the ${pick(rng, NOUNS)} rather than the number.`
}

function paragraph(rng: () => number): string {
  const n = 2 + Math.floor(rng() * 4)
  return Array.from({ length: n }, () => sentence(rng)).join(' ')
}

/**
 * THE CONSTRUCT CENSUS, and why these proportions and not others.
 *
 * Measured on the real tree on 2026-08-08 — counts of files containing each construct, out of 4,619
 * markdown files. Reproduced here because **the fake soil is only a stand-in for the real one to the
 * extent it carries the same things**, and Phase 5 needs it to stand in for a corpus of *damage*:
 * the old editor's destruction was per-construct, and a corpus missing a construct cannot detect
 * the loss of it.
 *
 * The first version of this generator carried tables, fences, blockquotes and lists — and **zero
 * frontmatter, zero wikilinks, zero task boxes, zero footnotes, zero images, one HTML tag.** Those
 * absences line up almost exactly with the destructive categories the old harness counts
 * (`frontmatter_destroyed`, `wikilinks_escaped`, `taskboxes_lost`, `footnotes_escaped`,
 * `images_lost`, `html_tags_lost`, `html_comments_lost`, `entities_introduced`). The mock tree was
 * built for *filesystem* hazards and is excellent at those; it was blind to markdown ones.
 *
 * **Frontmatter is the one that matters most:** 49% of the real tree carries it, and the old editor
 * silently flattened it in 944 files — a `---` block rendered as a thematic break plus a setext
 * heading. A damage corpus without frontmatter cannot see the headline defect.
 */
const CONSTRUCT_SHARE = {
  frontmatter: 0.49,   // 2,282 / 4,619
  codeFence: 0.16,     // 751
  blockquote: 0.14,    // 663
  table: 0.13,         // 616
  htmlTag: 0.10,       // 464
  wikilink: 0.054,     // 250
  taskBox: 0.031,      // 141
  /**
   * **THE RARE TAIL IS DELIBERATELY OVER-REPRESENTED, and that is not a fidelity failure.**
   *
   * Faithful proportions put images in 5 files and entities in 6, out of ~1,400 — the real tree's
   * own rates. That is representative and useless: a corpus with five instances of a construct
   * cannot measure damage to it, because five is inside the noise of anything that goes wrong for
   * an unrelated reason.
   *
   * Two different goals are in tension and only one of them is proportionality. For the common
   * constructs the corpus must look like the tree, so a percentage means something. For the rare
   * tail it must carry **enough instances to measure**, and the tree's own rate is the wrong
   * target. These four are raised to land around 15–20 files each; their real rates stay in the
   * comments so the divergence is visible rather than looking like a mistake.
   */
  htmlComment: 0.014,  // 66 real (1.4%) — already sufficient at this rate
  image: 0.012,        // 24 real (0.5%) — raised for sufficiency
  entity: 0.012,       // 20 real (0.4%) — raised
  footnote: 0.012,     // 19 real (0.4%) — raised
} as const

/** A generated document. Shapes mirror the archetypes the real tree is full of. */
function document(rng: () => number, title: string): string {
  const lines: string[] = []

  /**
   * Frontmatter first, because it must be the first bytes of the file or it is not frontmatter —
   * and "renders as a thematic break plus a setext heading instead" is the exact bug this exists
   * to catch.
   */
  if (rng() < CONSTRUCT_SHARE.frontmatter) {
    lines.push('---')
    lines.push(`title: ${title}`)
    lines.push(`status: ${pick(rng, ['draft', 'active', 'archived', 'blocked'])}`)
    if (rng() < 0.4) lines.push(`tags: [${pick(rng, NOUNS)}, ${pick(rng, NOUNS)}]`)
    if (rng() < 0.3) lines.push(`updated: 2026-0${1 + Math.floor(rng() * 8)}-1${Math.floor(rng() * 9)}`)
    lines.push('---', '')
  }

  lines.push(`# ${title}`, '')
  const sections = 2 + Math.floor(rng() * 4)

  // Drawn once per document — see the note in the section loop for why this is not per section.
  const carries = {
    table: rng() < CONSTRUCT_SHARE.table,
    codeFence: rng() < CONSTRUCT_SHARE.codeFence,
    blockquote: rng() < CONSTRUCT_SHARE.blockquote,
    htmlTag: rng() < CONSTRUCT_SHARE.htmlTag,
    wikilink: rng() < CONSTRUCT_SHARE.wikilink,
    taskBox: rng() < CONSTRUCT_SHARE.taskBox,
    htmlComment: rng() < CONSTRUCT_SHARE.htmlComment,
    image: rng() < CONSTRUCT_SHARE.image,
    entity: rng() < CONSTRUCT_SHARE.entity,
    footnote: rng() < CONSTRUCT_SHARE.footnote,
  }
  const inSection = (): number => Math.floor(rng() * sections)
  const tableSection = inSection()
  const fenceSection = inSection()
  const quoteSection = inSection()
  const taskSection = inSection()
  const linkSection = inSection()
  const htmlSection = inSection()

  for (let s = 0; s < sections; s += 1) {
    lines.push(`## ${pick(rng, NOUNS).replace(/^./, c => c.toUpperCase())}`, '')
    lines.push(paragraph(rng), '')

    /**
     * **Decided per document, not per section.** The census counts *files* containing a construct,
     * so drawing per section would multiply each share by the section count and put tables in a
     * third of the tree. Each construct is drawn once above and placed in whichever section comes
     * up, which is what makes the generated distribution match the measured one.
     */
    if (carries.table && s === tableSection) {
      lines.push('| Farm | Bushels | Note |', '|------|--------:|------|')
      lines.push(...Array.from({ length: 3 + Math.floor(rng() * 4) },
        () => `| ${pick(rng, FARMS)} | ${Math.floor(rng() * 9000 + 500)} | ${pick(rng, QUALIFIERS)} |`))
      lines.push('')
    }
    if (carries.codeFence && s === fenceSection) {
      lines.push('```', `intake  ${Math.floor(rng() * 5000)} bu/day`,
        'line    3400 bu/day', `delta   ${Math.floor(rng() * 1600) - 800}`, '```', '')
    }
    if (carries.blockquote && s === quoteSection) lines.push(`> ${sentence(rng)}`, '')

    if (carries.taskBox && s === taskSection) {
      // Unchecked and checked both — the old editor lost the box, not the line, so a corpus with
      // only one state cannot tell "unchecked became checked" from "the box survived".
      lines.push(`- [ ] ${sentence(rng)}`, `- [x] ${sentence(rng)}`, '')
    }
    if (carries.wikilink && s === linkSection) {
      lines.push(`See [[${pick(rng, BULK_PROJECTS)}]] and [the note](../${pick(rng, NOUNS)}.md).`, '')
    }
    if (carries.htmlTag && s === htmlSection) {
      lines.push(`<sub>${pick(rng, QUALIFIERS)}</sub> — recorded <b>before</b> the vote.`, '')
    }
    if (carries.htmlComment && s === htmlSection) {
      lines.push(`<!-- carried from the ${pick(rng, MONTHS)} minutes; do not reflow -->`, '')
    }
    if (carries.image && s === linkSection) {
      lines.push(`![${pick(rng, NOUNS)} yield](../assets/${pick(rng, NOUNS)}.png)`, '')
    }
    if (carries.entity && s === htmlSection) {
      lines.push(`Bins were 40&nbsp;kg &amp; stacked three high &mdash; see below.`, '')
    }

    if (rng() < 0.22) {
      lines.push(...Array.from({ length: 2 + Math.floor(rng() * 4) },
        () => `- ${sentence(rng)}`), '')
    }
  }

  if (carries.footnote) {
    // Definitions go at the end, which is where they are in the real tree and where a reflowing
    // editor is most likely to escape the `[^n]` marker.
    lines.push(`The ${pick(rng, NOUNS)} was disputed[^1].`, '', `[^1]: ${sentence(rng)}`, '')
  }

  return lines.join('\n')
}

