/**
 * THE MOCK SOIL — what is in it, and why each thing is there.
 *
 * ruled 2026-08-08: *"we can use real files that are not my actual files we can build like a
 * mock set or a copy of a folder and put it somewhere for testing purposes and if it fucks up it
 * fucked up."* This is that. It is the tree the app gets pointed at, driven through, and abused.
 * **Their real soil is never the target of anything in this build.**
 *
 * It is a *generator*, not a committed directory, for the same reason the grammar fixture is:
 * the generator is readable and a directory of 1,500 files is not. It is also **deterministic** —
 * no clock, no `Math.random` — so a path referenced in a test or a note keeps meaning the same
 * file next week.
 *
 * ## Three layers, and they answer different questions
 *
 * 1. **The spine** — hand-written documents in a fictional domain (an orchard co-operative), with
 *    real prose, real headings, real tables. Answers *"does a document look right on a screen?"*
 *    The domain is deliberately nothing like the user's actual work, so a mock file can never be
 *    mistaken for a real one at a glance.
 * 2. **The bulk** — generated documents that bring the tree to the scale of the real thing.
 *    Measured on the real soil 2026-08-08: **1,567 markdown files, 1,822 directories, 16 levels
 *    deep, median 2.2 KB, largest 71 KB.** Answers *"does it hold up at the size it will actually
 *    meet?"* — a tree of forty files proves nothing about indexing, watching or scrolling.
 * 3. **The hazards** — `zz-hazards/`, one folder per nasty case. Answers *"what happens when the
 *    filesystem is not polite?"* This is the layer worth the most: every one of these is a shape
 *    that exists in the wild, and each is a plausible way to lose a file.
 */

/** A plain file: folder-relative path, and its exact bytes. */
export type PlainFile = readonly [path: string, body: string]

/**
 * A hazard the generator must build with something other than `writeFile` — a symlink, a hard
 * link, a mode change, raw non-UTF-8 bytes, a file too large to sit in this source file.
 */
export interface SpecialEntry {
  readonly path: string
  /** Plain language, shown by `--list`. This is what the hazard is *for*. */
  readonly why: string
  readonly kind:
    | { readonly type: 'bytes'; readonly bytes: readonly number[] }
    | { readonly type: 'filled'; readonly size: number; readonly unit: string }
    | { readonly type: 'symlink'; readonly target: string; readonly relative: boolean }
    | { readonly type: 'hardlink'; readonly to: string }
    | { readonly type: 'mode'; readonly body: string; readonly mode: number }
    | { readonly type: 'dir-mode'; readonly mode: number }
    | { readonly type: 'empty-dir' }
}

